function iconParts(text) {
  if (typeof text !== 'string') return null;
  const parts = []; let start = 0;
  for (const match of text.matchAll(GLYPH_PATTERN)) {
    if (match.index > start) parts.push({ text: text.slice(start, match.index) });
    // Copyright and ordinary text symbols are not interface emoji.
    if (['©', '®', '™'].includes(match[0])) parts.push({text: match[0]});
    else parts.push({ icon: GLYPH_ICONS[match[0]] || 'sparkles' });
    start = match.index + match[0].length;
  }
  if (start < text.length) parts.push({ text: text.slice(start) });
  return parts;
}
