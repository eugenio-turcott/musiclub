import fs from 'node:fs/promises';
import {CURATED_PATCH_NOTES} from '../src/data/patchNotesData.js';
import {consolidateMajorReleases,versionParts,releaseBody} from './lib/major-releases.mjs';
const target=process.argv[2];
const [major,minor,patch]=versionParts(target);
if(minor||patch||!/^v\d+\.0\.0$/.test(target))throw new Error('Official releases require a vX.0.0 tag');
const release=consolidateMajorReleases(CURATED_PATCH_NOTES).find(note=>note.major===major);
if(!release)throw new Error(`No consolidated notes for ${target}`);
await fs.writeFile('RELEASE_BODY.md',releaseBody(release));
console.log(`Prepared ${release.version}`);
