import fs from 'node:fs/promises';
import artwork from '../src/utils/interfaceArtwork.cjs';
import {ANNUAL_ICON_SURFACES,contrastingInk} from '../src/utils/annualIconContrast.mjs';
let css='/* Generated by scripts/build-annual-icon-styles.mjs. Native icon hues with at least 3.5:1 contrast across the annual backgrounds. */\n';
for(const [surface,backgrounds] of Object.entries(ANNUAL_ICON_SURFACES)){
  const selector=`[data-annual-icons="${surface}"]`+(surface==='dark'?', [data-annual-icons] footer':'');
  css+=selector+'{'+Object.entries(artwork.ICON_COLORS).map(([name,color])=>`--annual-${name}:${contrastingInk(color,backgrounds)};`).join('')+'}\n';
}
css+='[data-annual-icons][data-annual-icons] .ui-icon[data-ui-icon]{color:var(--annual-icon-ink,currentColor)!important}\n';
for(const name of Object.keys(artwork.ICON_COLORS))css+=`[data-annual-icons] .ui-icon[data-ui-icon="${name}"]{--annual-icon-ink:var(--annual-${name})}\n`;
await fs.writeFile(new URL('../src/styles/annual-icons.css',import.meta.url),css);
